#!/usr/bin/env python3
"""What install.sh writes outside the checkout: managed blocks, link destinations, and the install manifest.

Usage: install_blocks.py upsert <home> <checkout> | prepare <home> <checkout> [config dir ...]
       install_blocks.py config-dirs <home> [config dir ...]
`upsert` writes the memory block into ~/.claude/CLAUDE.md and ~/.codex/AGENTS.md and the imports block,
generated from the checkout's `.claude/CLAUDE.md`, into CLAUDE.md (never into another config
dir's CLAUDE.md); `expected(checkout, home)` is what `crew-doctor.py` compares an install against.
`prepare` creates the directories install links into and records the ones it created,
the checkout and the Claude config dirs (`config_dirs`) in `~/.agent/install-manifest.json`; the
settings mergers add the entries they added there (`record`). `config-dirs` prints the config dirs,
~/.claude first. `LINKS` is where install writes links, read by install (`prepare`), `uninstall.py` and
`crew-doctor.py`.
"""
from __future__ import annotations

import json
import os
import re
import sys
import tempfile
import time
from pathlib import Path

# (directory under HOME, depth): where install.sh writes links. `.claude` holds the agents and skills
# directory links into `.cursor`; the `.agent` directories are data and are never removed.
LINKS = ((".agent", 1), (".agent/bin", 1), (".cursor/rules", 1), (".cursor/agents", 1), (".cursor/skills", 3),
         (".claude/hooks", 1), (".claude", 1))
MANIFEST = Path(".agent") / "install-manifest.json"
# A hook command's script under the managed hooks directory: `$HOME/`, `${HOME}/`, `~/` or an absolute
# prefix (which `hook_scripts` keeps only when it is this HOME), as `hooks_retirement.MANAGED_PATH` reads it.
HOOK_SCRIPT = re.compile(r"""(\$HOME|\$\{HOME\}|~|/[^\s"';]*)/(\.claude/hooks/\S+?\.sh)""")

MEMORY = ("<!-- el-capitan:memory -->\n"
          "Claude Code and Cursor inject session memory at session start; other harnesses run "
          "`~/.agent/bin/crew-mem.py context --mode session` at task start. "
          "Follow `~/.cursor/skills/crew-memory/references/contract.md`.\n"
          "<!-- /el-capitan:memory -->")
TARGETS = (Path(".claude") / "CLAUDE.md", Path(".codex") / "AGENTS.md")
NAMES = ("memory", "imports")


def global_rule_imports(source: Path) -> str:
    """The `@` imports the checkout's `.claude/CLAUDE.md` names, as a fenced block for the global file.

    `.claude/CLAUDE.md` is project-scoped, so in any other checkout Claude Code loads only
    `~/.claude/CLAUDE.md`; an always-on rule is invisible there unless the global file imports it. A
    glob-scoped rule or an on-demand skill is not imported: its one-line `Read ~/.cursor/... before`
    pointer is copied instead, so other repositories still learn when to read it.
    """
    project = source / ".claude" / "CLAUDE.md"
    if not project.is_file():
        return ""
    text = project.read_text(errors="replace")
    targets: list[str] = []
    for target in re.findall(r"@(\S+\.mdc)", text):
        if target not in targets:
            targets.append(target)
    pointers = re.findall(r"^Read ~/\.cursor/(?:rules/\S+\.mdc|skills/[\w-]+/SKILL\.md) before .+$", text, re.M)
    if not targets and not pointers:
        return ""
    lines = ["<!-- el-capitan:imports -->",
             "<!-- Generated by install.sh from .claude/CLAUDE.md; edits here are overwritten. -->"]
    lines += [f"@{target}" for target in targets]
    lines += pointers
    lines.append("<!-- /el-capitan:imports -->")
    return "\n".join(lines)


def recorded_config_dirs(home: Path) -> list[Path]:
    """The config dirs the manifest records (absolute paths), ~/.claude among them or not."""
    recorded = (load_manifest(home) or {}).get("config_dirs", [])
    return [Path(name) for name in recorded if isinstance(name, str)] if isinstance(recorded, list) else []


def config_dirs(home: Path, extra: tuple[str, ...] | list[str] = ()) -> list[Path]:
    """The Claude config dirs install covers, one per real path: ~/.claude, each recorded one that still exists,
    then `extra` (named by this run, created when missing)."""
    named = [Path(os.path.abspath(os.path.expanduser(name))) for name in extra]
    found: dict[str, Path] = {}
    for directory in [home / ".claude", *(d for d in recorded_config_dirs(home) if d.is_dir()), *named]:
        found.setdefault(os.path.realpath(directory), directory)
    return list(found.values())


def settings_section(home: Path, directory: Path) -> str:
    """The manifest section of a config dir's settings merge: `claude_settings`, or `claude_settings:<dir>`."""
    if os.path.realpath(directory) == os.path.realpath(home / ".claude"):
        return "claude_settings"
    return f"claude_settings:{os.path.abspath(directory)}"


def instruction_files(home: Path) -> list[Path]:
    """The files the blocks go into: `TARGETS` only.

    Another config dir gets no block: Claude Code reads the user CLAUDE.md from ~/.claude even with
    `CLAUDE_CONFIG_DIR` set (TOOLS.md "Claude config dirs"), so a second copy could load every rule twice.
    """
    return [home / target for target in TARGETS]


def expected(source: Path, home: Path) -> dict[Path, dict[str, str]]:
    """Per instruction file (absolute), the block bodies a current install holds."""
    imports = global_rule_imports(source)
    return {path: {"memory": MEMORY, **({"imports": imports} if imports and path.name == "CLAUDE.md" else {})}
            for path in instruction_files(home)}


def span(text: str, name: str) -> tuple[int, int] | None:
    """The start and end offsets of the fenced block `name`, or None when the file has none."""
    start_marker, end_marker = f"<!-- el-capitan:{name} -->", f"<!-- /el-capitan:{name} -->"
    start, end = text.find(start_marker), text.find(end_marker)
    return (start, end + len(end_marker)) if start >= 0 and end >= start else None


def current(text: str, name: str) -> str | None:
    """The block `name` as the file holds it, markers included, or None."""
    found = span(text, name)
    return text[found[0]:found[1]] if found else None


def upsert(text: str, name: str, body: str) -> str:
    """Replace the fenced block in place, or append it; idempotent on every run.

    `body` carries no trailing newline, so both paths normalize to exactly one newline after the
    closing marker and collapse any run of blank lines that follows it.
    """
    found = span(text, name)
    if found:
        rest = text[found[1]:].lstrip("\n")
        return text[:found[0]] + body + ("\n" + rest if rest else "\n")
    return text.rstrip() + "\n\n" + body + "\n"


def remove(text: str, name: str) -> str:
    """The text without the block `name` and the blank lines `upsert` put around it."""
    found = span(text, name)
    if not found:
        return text
    before, after = text[:found[0]].rstrip("\n"), text[found[1]:].lstrip("\n")
    return before + "\n\n" + after if before and after else before or after


def write_atomically(target: Path, text: str) -> None:
    """Keep the file's mode and follow a symlink, so a dotfiles-managed CLAUDE.md keeps its link."""
    target = target.resolve() if target.is_symlink() else target
    mode = target.stat().st_mode & 0o777 if target.exists() else 0o644
    target.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(prefix=".install-", dir=target.parent)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
            handle.write(text)
        os.chmod(temporary, mode)
        os.replace(temporary, target)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def write_json(data: object, path: Path) -> None:
    """`data` as indented JSON, atomically, keeping the file's mode and a symlink (`write_atomically`)."""
    write_atomically(Path(path), json.dumps(data, indent=2) + "\n")


def install(home: Path, source: Path) -> None:
    for path, blocks in expected(source, home).items():
        text = path.read_text() if path.exists() else ""
        for name, body in blocks.items():
            text = upsert(text, name, body)
        write_atomically(path, text.rstrip() + "\n")


def block_removals(home: Path) -> list[tuple[Path, str | None]]:
    """Each instruction file holding a managed block, with its text without them (None: delete the file)."""
    changes = []
    for path in instruction_files(home):
        if not path.is_file():
            continue
        original = path.read_text()
        text = original
        for name in NAMES:
            text = remove(text, name)
        if text != original:
            keep = text.strip() or path.is_symlink()
            changes.append((path, (text.rstrip() + "\n" if text.strip() else "") if keep else None))
    return changes


class ManifestError(ValueError):
    """An unreadable install manifest: the caller names the file and changes nothing."""


def load_manifest(home: Path) -> dict | None:
    """`~/.agent/install-manifest.json`, or None when install never wrote one (an install from before it)."""
    path = home / MANIFEST
    if not path.exists():
        return None
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as error:
        raise ManifestError(f"cannot read {path}: {error}") from error
    if not isinstance(data, dict):
        raise ManifestError(f"{path} is not a JSON object")
    return data


def union(old: object, new: object) -> object:
    """`new` merged into `old`: lists gain the items they lack, objects merge per key, a scalar keeps its first."""
    if old is None:
        return new
    if isinstance(new, dict) and isinstance(old, dict):
        return {**old, **{key: union(old.get(key), value) for key, value in new.items()}}
    if isinstance(new, list) and isinstance(old, list):
        return old + [item for item in new if item not in old]
    return old


def record(home: Path, section: str, added: dict, present: dict) -> None:
    """Add what one install step added to the manifest; it stays the union of every install's additions.

    `present` is the template's entries the file already held. On the first record after an install
    from before the manifest (`legacy`), those may be that install's, so they are kept as `legacy`:
    uninstall compares them with the oldest backup of the file.
    """
    manifest = load_manifest(home) or {"version": 1}
    if section not in manifest and manifest.get("legacy"):
        added = {**added, "legacy": present}
    manifest[section] = union(manifest.get(section), added)
    write_json(manifest, home / MANIFEST)


def backup(path: Path, text: str) -> Path:
    """Write `text` to a new `<path>.bak.<epoch>`, never over an earlier backup."""
    stamp = int(time.time())
    while Path(f"{path}.bak.{stamp}").exists():
        stamp += 1
    target = Path(f"{path}.bak.{stamp}")
    target.write_text(text, encoding="utf-8")
    return target


def oldest_backup(path: Path, before: float | None = None) -> Path | None:
    """The earliest `<path>.bak.<epoch>`, only among those written (mtime) before `before` when given, or None."""
    found = [(int(p.name.rsplit(".", 1)[1]), p) for p in path.parent.glob(f"{path.name}.bak.*")
             if p.name.rsplit(".", 1)[1].isdigit()]
    found = [(stamp, p) for stamp, p in found if before is None or p.stat().st_mtime < before]
    return min(found)[1] if found else None


def target_of(link: Path) -> str:
    """The link's target as a real path, resolved as far as it exists (a dangling target is still a path)."""
    target = os.readlink(link)
    return os.path.realpath(target if os.path.isabs(target) else os.path.join(os.path.dirname(link), target))


def inside(path: str, roots: set[str]) -> bool:
    return any(path == root or path.startswith(root + os.sep) for root in roots)


def layout_links(home: Path) -> list[Path]:
    """Every symlink under the install layout (`LINKS`), never descending through a link."""
    def walk(directory: Path, depth: int) -> list[Path]:
        if depth < 1 or directory.is_symlink() or not directory.is_dir():
            return []
        found = []
        for entry in sorted(directory.iterdir()):
            found += [entry] if entry.is_symlink() else walk(entry, depth - 1)
        return found
    return sorted({link for name, depth in LINKS for link in walk(home / name, depth)})


def install_dirs(home: Path, source: Path) -> list[Path]:
    """The directories install links into, parents first (the `.agent` data directories are not among them)."""
    names = [".claude", ".codex", ".cursor", *(name for name, _ in LINKS if not name.startswith(".agent"))]
    skills = source / ".cursor" / "skills"
    for skill in sorted(skills.iterdir()) if skills.is_dir() else []:
        if skill.is_dir():
            names.append(f".cursor/skills/{skill.name}")
            if (skill / "references").is_dir():
                names.append(f".cursor/skills/{skill.name}/references")
    return [home / name for name in dict.fromkeys(names)]


def prepare(home: Path, source: Path, extra: tuple[str, ...] | list[str] = ()) -> None:
    """Create the install directories; record those it created, every checkout installed from and the config dirs.

    A config dir is created only when this run names it (`extra`), and recorded in `created_config_dirs` (absolute
    paths) so uninstall removes it once empty. A recorded dir that no longer exists is dropped, with a line.

    No manifest while links into this checkout exist means an install from before the manifest: it is
    marked `legacy` with the time it was found, so the settings mergers keep the template entries they find
    for uninstall to judge, and only a backup older than that time counts as what the user had.
    """
    real = os.path.realpath(source)
    manifest = load_manifest(home)
    legacy = manifest is None and any(inside(target_of(link), {real, str(source)}) for link in layout_links(home))
    manifest = manifest or {"version": 1, **({"legacy": time.time()} if legacy else {})}
    created = []
    for directory in install_dirs(home, source):
        if not os.path.lexists(directory):
            directory.mkdir(parents=True)
            created.append(str(directory.relative_to(home)))
    dirs, made = config_dirs(home, extra), []
    named = {os.path.realpath(os.path.abspath(os.path.expanduser(name))) for name in extra}
    for directory in recorded_config_dirs(home):
        if not directory.is_dir() and os.path.realpath(directory) not in named:
            print(f"  dropped {directory}: it no longer exists")
    for directory in dirs[1:]:
        if not os.path.lexists(directory):
            directory.mkdir(parents=True)
            made.append(str(directory))
    manifest["dirs"] = union(manifest.get("dirs"), created)
    manifest["created_config_dirs"] = union(manifest.get("created_config_dirs"), made)
    manifest["checkouts"] = union(manifest.get("checkouts"), [real, str(source)])
    manifest["config_dirs"] = [str(directory) for directory in dirs]
    (home / MANIFEST).parent.mkdir(parents=True, exist_ok=True)
    write_json(manifest, home / MANIFEST)


def hook_scripts(commands: list[str], home: Path) -> list[str]:
    """The `.claude/hooks/...` script paths (relative to HOME) that hook commands run.

    `$HOME/`, `${HOME}/` and `~/` forms count, and an absolute path when it resolves under `home`.
    """
    real = os.path.realpath(home)
    return [script for command in commands for prefix, script in HOOK_SCRIPT.findall(command)
            if not prefix.startswith("/") or os.path.realpath(prefix) == real]


def commands_in(data: object) -> list[str]:
    """Every `command` string anywhere in a settings document, whatever its shape."""
    if isinstance(data, dict):
        own = [data["command"]] if isinstance(data.get("command"), str) else []
        return own + [c for value in data.values() for c in commands_in(value)]
    if isinstance(data, list):
        return [c for value in data for c in commands_in(value)]
    return []


def main(argv: list[str]) -> int:
    try:
        if len(argv) == 3 and argv[0] == "upsert":
            install(Path(argv[1]), Path(argv[2]))
            return 0
        if len(argv) >= 3 and argv[0] == "prepare":
            prepare(Path(argv[1]), Path(argv[2]), argv[3:])
            return 0
        if len(argv) >= 2 and argv[0] == "config-dirs":
            print("\n".join(str(directory) for directory in config_dirs(Path(argv[1]), argv[2:])))
            return 0
    except (OSError, ManifestError) as error:
        print(f"install_blocks: {error}", file=sys.stderr)
        return 2
    print("usage: install_blocks.py upsert <home> <checkout> | prepare <home> <checkout> [config dir ...] | "
          "config-dirs <home> [config dir ...]", file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
